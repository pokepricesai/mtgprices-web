CREATE INDEX IF NOT EXISTS mtg_oracle_cards_name_idx           ON mtg_oracle_cards(name);
CREATE INDEX IF NOT EXISTS mtg_oracle_cards_layout_idx         ON mtg_oracle_cards(layout);

CREATE INDEX IF NOT EXISTS mtg_printings_oracle_card_id_idx    ON mtg_printings(oracle_card_id);
CREATE INDEX IF NOT EXISTS mtg_printings_set_id_idx            ON mtg_printings(set_id);
CREATE INDEX IF NOT EXISTS mtg_printings_set_code_idx          ON mtg_printings(set_code);
CREATE INDEX IF NOT EXISTS mtg_printings_set_collector_idx     ON mtg_printings(set_code, collector_number);
CREATE INDEX IF NOT EXISTS mtg_printings_released_at_idx       ON mtg_printings(released_at);

-- (printing_id, finish) UNIQUE already provides an index on printing_id.

CREATE INDEX IF NOT EXISTS mtg_oracle_legalities_format_legality_idx
  ON mtg_oracle_legalities(format, legality);

-- (provider, identifier_type, identifier_value) UNIQUE already indexes this.

CREATE INDEX IF NOT EXISTS mtg_price_observations_finish_date_idx
  ON mtg_price_observations(printing_finish_id, observed_on);
CREATE INDEX IF NOT EXISTS mtg_price_observations_date_idx
  ON mtg_price_observations(observed_on);
CREATE INDEX IF NOT EXISTS mtg_price_observations_provider_date_idx
  ON mtg_price_observations(provider, observed_on);

-- ─── RLS policies ───────────────────────────────────────────────────────────
