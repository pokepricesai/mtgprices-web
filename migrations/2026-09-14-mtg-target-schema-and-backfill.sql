-- ============================================================================
-- SCHEMA-ONLY MIGRATION — no backfill.
-- ============================================================================
-- The legacy tables (mtg_sets, mtg_cards, mtg_daily_prices, mtg_card_trends)
-- are NOT copied into the target tables. All seven target tables are
-- expected to be EMPTY after this migration applies. That is intentional:
--
--   * Stage 1B (Python scraper repo) populates mtg_sets/mtg_oracle_cards/
--     mtg_printings/mtg_printing_finishes/mtg_oracle_legalities from a
--     fresh Scryfall bulk pull.
--   * Stage 1C (Python scraper repo) populates mtg_external_identifiers
--     and mtg_price_observations from fresh MTGJSON downloads
--     (AllIdentifiers / AllPrintings for reconciliation, AllPrices for
--     the previous ~90 days, AllPricesToday appended daily).
--   * mtg_rulings is populated by whichever pipeline delivers
